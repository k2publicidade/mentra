import { test, expect } from '@playwright/test';
import crypto from 'node:crypto';
const account = () => ({name:'Teste de aceite',email:`aceite-${crypto.randomUUID()}@example.com`,password:crypto.randomBytes(20).toString('hex'),timezone:'America/Sao_Paulo'});
async function register(request) { const result = await request.post('/api/auth/register',{data:account()}); expect(result.status()).toBe(201); return (await result.json()).user; }
test('isolamento real entre contas e undo protegido', async ({playwright}) => {
  const a = await playwright.request.newContext({baseURL:'http://127.0.0.1:3100'});
  const b = await playwright.request.newContext({baseURL:'http://127.0.0.1:3100'});
  await register(a); await register(b);
  const saved=await a.post('/api/items',{data:{type:'memory',title:'Dado privado de aceite',notes:'isolamento',source:'manual'}});
  expect(saved.ok()).toBeTruthy(); const {item,undoId}=await saved.json();
  expect((await (await b.get('/api/items')).json()).items).toHaveLength(0);
  expect((await b.patch(`/api/items/${item.id}`,{data:{title:'intrusão'}})).status()).toBe(404);
  expect((await b.delete(`/api/items/${item.id}`)).status()).toBe(404);
  expect((await b.post(`/api/undo/${undoId}`,{data:{}})).status()).toBe(404);
  expect((await (await a.get('/api/items')).json()).items[0].title).toBe('Dado privado de aceite');
  await a.delete('/api/account',{data:{confirmation:'EXCLUIR'}}); await b.delete('/api/account',{data:{confirmation:'EXCLUIR'}});
  await a.dispose(); await b.dispose();
});
test('captura, consulta, correção sem duplicação e privacidade',async({request})=>{
  await register(request);
  const id=crypto.randomUUID();
  const capture=await request.post('/api/chat',{data:{text:'Me lembra sexta de enviar o contrato.',requestId:id}});
  expect(capture.ok()).toBeTruthy(); const body=await capture.json(); expect(body.reply).toBeTruthy(); expect(body.clarification).toBe(true);
  expect((await (await request.get('/api/items')).json()).items).toHaveLength(0);
  const repeated=await request.post('/api/chat',{data:{text:'Me lembra sexta de enviar o contrato.',requestId:id}}); expect(await repeated.json()).toEqual(body);
  const resolved=await request.post('/api/chat',{data:{text:'às 14',requestId:crypto.randomUUID()}}); expect(resolved.ok()).toBeTruthy(); expect((await resolved.json()).items).toHaveLength(1);
  let items=(await (await request.get('/api/items')).json()).items; expect(items).toHaveLength(1); const originalId=items[0].id; const originalDate=items[0].dueAt;
  const correction=await request.post('/api/chat',{data:{text:'Não, sábado.',requestId:crypto.randomUUID()}}); expect(correction.ok()).toBeTruthy();
  items=(await (await request.get('/api/items')).json()).items; expect(items).toHaveLength(1); expect(items[0].id).toBe(originalId); expect(items[0].dueAt).not.toBe(originalDate);
  const exported=await request.get('/api/export'); expect(exported.ok()).toBeTruthy(); expect(await exported.text()).toContain(originalId);
  const ics=await request.get('/api/calendar.ics'); expect(ics.ok()).toBeTruthy(); expect(await ics.text()).toContain('BEGIN:VCALENDAR');
  const undo=await request.post(`/api/undo/${(await correction.json()).undoId}`,{data:{}}); expect(undo.ok()).toBeTruthy();
  items=(await (await request.get('/api/items')).json()).items; expect(items[0].dueAt).toBe(originalDate);
  expect((await request.delete('/api/account',{data:{confirmation:'EXCLUIR'}})).ok()).toBeTruthy(); expect((await request.get('/api/auth/me')).status()).toBe(401);
});
