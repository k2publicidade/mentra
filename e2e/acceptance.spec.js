test('memória manual com origem, erro de gravação visível e exclusão',async({page})=>{
  await register(page.request); await page.request.patch('/api/profile',{data:{onboarded:true}});
  await page.goto('/app');
  await page.getByRole('navigation',{name:'Navegação principal'}).getByRole('button',{name:'Vida',exact:true}).click();
  await page.getByRole('button',{name:'Novo registro',exact:true}).click();
  const dialog=page.getByRole('dialog');
  await dialog.getByLabel('Tipo',{exact:true}).selectOption('memory');
  await dialog.getByLabel('Título',{exact:true}).fill('Preferência de teste');
  await dialog.getByLabel('Origem da memória').fill('Informado no teste de aceite');
  await page.route('**/api/items',async route=>{if(route.request().method()==='POST')await route.fulfill({status:500,contentType:'application/json',body:JSON.stringify({error:'Falha controlada de persistência'})});else await route.continue();});
  await dialog.getByRole('button',{name:'Salvar registro'}).click();
  await expect(dialog.getByRole('alert')).toContainText('Falha controlada');
  expect((await (await page.request.get('/api/items')).json()).items).toHaveLength(0);
  await page.unroute('**/api/items');
  await dialog.getByRole('button',{name:'Salvar registro'}).click();
  await expect(dialog).toHaveCount(0);
  await expect(page.locator('.item-row')).toContainText('Informado no teste de aceite');
  page.once('dialog',d=>d.accept());
  await page.getByRole('button',{name:'Excluir Preferência de teste',exact:true}).click();
  await expect(page.locator('.item-row')).toHaveCount(0);
  expect((await (await page.request.get('/api/items')).json()).items).toHaveLength(0);
  await page.request.delete('/api/account',{data:{confirmation:'EXCLUIR'}});
});
